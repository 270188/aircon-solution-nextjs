-- Agenda del equipo: fichas de clientes (para recordar su mantenimiento) y datos internos de cada cita.
-- Con "if not exists" porque la misma estructura la crea también la API de Netlify.

create table if not exists clients (
    id               bigint generated by default as identity primary key,
    name             varchar(160)  not null,
    phone            varchar(30),
    district         varchar(80),
    address          varchar(200),
    equipment        varchar(300),
    installed_on     date,
    last_maintenance date,
    frequency_months integer       not null default 6,
    last_reminder    date,
    notes            varchar(1000),
    created_at       timestamp with time zone not null default now(),
    updated_at       timestamp with time zone not null default now()
);

alter table bookings add column if not exists client_id bigint references clients (id) on delete set null;
alter table bookings add column if not exists technician varchar(80);
alter table bookings add column if not exists amount numeric(12, 2);
-- WEB: la reservó el cliente en la página; PANEL: la agendó el equipo.
alter table bookings add column if not exists source varchar(10) not null default 'WEB';

create index if not exists idx_bookings_client on bookings (client_id);

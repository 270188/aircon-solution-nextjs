-- Comprobantes de pago (facturas y boletas) emitidos desde el panel

create table invoices (
    id                  bigint generated by default as identity primary key,
    doc_type            varchar(10)   not null,
    series              varchar(4)    not null,
    number              integer       not null,
    issue_date          date          not null,
    currency            varchar(3)    not null default 'PEN',
    customer_doc_type   varchar(1)    not null,
    customer_doc_number varchar(15),
    customer_name       varchar(200)  not null,
    customer_address    varchar(250),
    customer_email      varchar(160),
    booking_id          bigint references bookings (id),
    subtotal            numeric(12, 2) not null,
    igv                 numeric(12, 2) not null,
    total               numeric(12, 2) not null,
    status              varchar(15)   not null,
    observations        varchar(500),
    sunat_description   varchar(500),
    pdf_url             varchar(500),
    hash                varchar(100),
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    constraint uq_invoice_number unique (series, number)
);

create index idx_invoices_issue_date on invoices (issue_date);

create table invoice_items (
    id          bigint generated by default as identity primary key,
    invoice_id  bigint         not null references invoices (id) on delete cascade,
    line_no     integer        not null,
    description varchar(250)   not null,
    quantity    numeric(12, 2) not null,
    unit_price  numeric(12, 2) not null,
    unit_value  numeric(16, 6) not null,
    subtotal    numeric(12, 2) not null,
    igv         numeric(12, 2) not null,
    total       numeric(12, 2) not null
);

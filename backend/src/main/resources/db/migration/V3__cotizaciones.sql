-- Cotizaciones (presupuestos) que se envían al cliente antes de hacer el trabajo

create table quotes (
    id               bigint generated by default as identity primary key,
    number           integer       not null unique,
    issue_date       date          not null,
    valid_until      date          not null,
    customer_doc     varchar(15),
    customer_name    varchar(200)  not null,
    customer_contact varchar(120),
    customer_phone   varchar(20),
    customer_email   varchar(160),
    customer_address varchar(250),
    booking_id       bigint references bookings (id),
    subtotal         numeric(12, 2) not null,
    igv              numeric(12, 2) not null,
    total            numeric(12, 2) not null,
    -- true: los precios ya incluyen IGV; false: el IGV (18 %) se suma al precio
    prices_include_igv boolean     not null default true,
    status           varchar(15)   not null,
    notes            varchar(1500),
    created_at       timestamp with time zone not null,
    updated_at       timestamp with time zone not null
);

create table quote_items (
    id          bigint generated by default as identity primary key,
    quote_id    bigint         not null references quotes (id) on delete cascade,
    line_no     integer        not null,
    description varchar(250)   not null,
    quantity    numeric(12, 2) not null,
    -- precio tal como se cotizó (con o sin IGV según quotes.prices_include_igv)
    unit_price  numeric(12, 2) not null,
    subtotal    numeric(12, 2) not null,
    igv         numeric(12, 2) not null,
    total       numeric(12, 2) not null
);

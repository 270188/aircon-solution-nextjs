-- Envío directo a SUNAT: se guardan el XML firmado, la constancia (CDR) y los tickets de anulación.

alter table invoices add column signed_xml varchar(200000);
alter table invoices add column cdr_zip varchar(100000);
alter table invoices add column sunat_ticket varchar(40);

create table sunat_summaries (
    id          bigint generated by default as identity primary key,
    kind        varchar(2)  not null,
    issue_date  date        not null,
    correlative integer     not null,
    invoice_id  bigint      not null references invoices (id),
    ticket      varchar(40),
    created_at  timestamp with time zone not null,
    constraint uq_sunat_summary unique (kind, issue_date, correlative)
);
